SELECT  A.[BusinessEntityID]
      ,A.[NationalIDNumber]
      ,A.[LoginID]
      ,A.[OrganizationNode]
      ,A.[OrganizationLevel]
      ,A.[JobTitle]
      ,A.[BirthDate]
      ,A.[MaritalStatus]
      ,A.[Gender]
      ,A.[HireDate]
      ,A.[SalariedFlag]
      ,A.[VacationHours]
      ,A.[SickLeaveHours]
      ,A.[CurrentFlag]
      ,A.[rowguid]
      ,A.[ModifiedDate]
      ,B.[BusinessEntityID]
      ,B.[DepartmentID]
      ,B.[ShiftID]
      ,B.[StartDate]
      ,B.[EndDate]
      ,B.[ModifiedDate]
      ,C.[BusinessEntityID]
      ,C.[RateChangeDate]
      ,C.[Rate]
      ,C.[PayFrequency]
      ,C.[ModifiedDate]
      ,D.[JobCandidateID]
      ,D.[BusinessEntityID]
      ,D.[Resume]
      ,D.[ModifiedDate]
      ,E.[DepartmentID]
      ,E.[Name]
      ,E.[GroupName]
      ,E.[ModifiedDate]
  FROM [AdventureWorks2025].[HumanResources].[Employee] A
  LEFT JOIN [AdventureWorks2025].[HumanResources].[EmployeeDepartmentHistory]B ON A.BusinessEntityID = B.BusinessEntityID
  LEFT JOIN [AdventureWorks2025].[HumanResources].[EmployeePayHistory] C ON A.BusinessEntityID = C.BusinessEntityID
  LEFT JOIN [AdventureWorks2025].[HumanResources].[JobCandidate] D ON A.BusinessEntityID = D.BusinessEntityID
  LEFT JOIN [AdventureWorks2025].[HumanResources].[Department] E ON A.ModifiedDate = E.ModifiedDate